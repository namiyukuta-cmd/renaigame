'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const sourcePath='simulation/AI_GENERATION_ENTRY.md';
const targetDir='simulation-lite/character-notes';
function sections(source){
  const headings=[...source.matchAll(/^(#{1,6})\s+(.+)$/gm)];
  const notes={};
  for(let i=0;i<headings.length;i++){
    const current=headings[i],id=current[2].match(/^(char_\d{3})\b/)?.[1];
    if(!id)continue;
    const next=headings.slice(i+1).find(heading=>heading[1].length<=current[1].length);
    (notes[id]||=[]).push(source.slice(current.index,next?.index??source.length).trim());
  }
  return notes;
}
function render(id,parts){
  const content=parts.length?parts.join('\n\n'):'共通入口に、この人物専用の追加開始設定はありません。人物JS・behaviorと現在スロットのプロフィール・実ログを使います。';
  // Links in the original entry are relative to simulation/, while these files
  // live two directories below the repository root. The prose stays verbatim.
  const linked=content.replace(/\]\((?!https?:|#)([^)]+)\)/g,(_,target)=>{
    const [file,anchor]=target.split('#');
    const canonical=/^(?:simulation|simulation-lite|js)\//.test(file)?file:path.posix.join('simulation',file);
    return ']('+path.posix.relative(targetDir,canonical)+(anchor?'#'+anchor:'')+')';
  });
  return '# '+id+'：選択中の人物の開始・継続メモ\n\n'+
    '<!-- Generated by simulation/scripts/generate_lite_ai_notes.cjs. Do not edit. -->\n\n'+
    '正本：`'+sourcePath+'`の、このIDに対応する全節を抽出しています。共通規則は`simulation-lite/AI_ENTRY.md`と、その必須資料を適用します。今回のプロフィール・実ログを優先し、別人物の設定は混ぜません。\n\n'+linked+'\n';
}
function build(){
  const registry=fs.readFileSync(path.join(root,'simulation/js/simulation_characters.js'),'utf8');
  const ids=[...registry.matchAll(/"simulation_character_(\d{3})\.js"/g)].map(match=>'char_'+match[1]);
  const notes=sections(fs.readFileSync(path.join(root,sourcePath),'utf8'));
  return Object.fromEntries(ids.map(id=>[id+'.md',render(id,notes[id]||[])]));
}
function main(args){
  if(args.length>1||(args.length===1&&args[0]!=='--check'))throw Error('使い方: generate_lite_ai_notes.cjs [--check]');
  const expected=build(),dir=path.join(root,targetDir);
  if(args[0]==='--check'){
    const actual=fs.existsSync(dir)?fs.readdirSync(dir).filter(name=>/^char_\d{3}\.md$/.test(name)).sort():[];
    if(JSON.stringify(actual)!==JSON.stringify(Object.keys(expected).sort())||Object.entries(expected).some(([name,text])=>fs.readFileSync(path.join(dir,name),'utf8')!==text))throw Error('軽量版の人物メモをgenerate_lite_ai_notes.cjsで再生成してください。');
    console.log('PASS: lightweight character notes contain the current canonical sections');
  }else{
    fs.mkdirSync(dir,{recursive:true});
    for(const name of fs.readdirSync(dir))if(/^char_\d{3}\.md$/.test(name)&&!Object.hasOwn(expected,name))fs.unlinkSync(path.join(dir,name));
    for(const [name,text] of Object.entries(expected))fs.writeFileSync(path.join(dir,name),text);
  }
}
if(require.main===module){try{main(process.argv.slice(2));}catch(error){console.error(error.message);process.exitCode=1;}}
module.exports={sections,render,build,main};
