'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const C=require('../../simulation-lite/core.js'),runtime=require('../js/ai_turn_runtime.js'),reviewedActions=require('./helpers/review_fixture.cjs');
const root=path.resolve(__dirname,'../..'),read=file=>fs.readFileSync(path.join(root,file),'utf8');
const initialState=JSON.parse(read('simulation/state/templates/char_016_initial_state.json'));
const save=C.createSave({profile:{name:'テスト主人公',age:'31',free:'テスト用の設定'},characterId:'char_016',partnerName:'アーサー',initialState,saveId:'lite_test'});
const sources=Object.fromEntries([...runtime.sourcePaths('char_016'),'simulation/js/simulation_save.js'].map(file=>[file,read(file)]));
const runner=runtime.createRuntime({sources,save,saveId:save.saveId,characterId:'char_016',recordIndices:[]});
const input={protagonistInput:'Chapter1\n「ありがとう。」',changes:{gratitude:2},evidence:{gratitude:'ありがとう。'}};
const args=runner.buildArgs(input),run=runner.runTurn(input),engine=runner.scope.RenaiGameTurnEngine;
const story='Chapter 1\n英国・店内／2026年10月17日（土）／15:00／15℃\n\nアーサーは頷いた。';
const actions=reviewedActions(engine,args,story),released=runner.releaseStory(input,run.packet,story,actions);
vm.runInNewContext(sources['simulation/js/simulation_save.js'],{window:runner.scope});
const bundle=runner.scope.RenaiGameSave.createChapterBundleV2({args,packet:run.packet,verification:released.verification,validation:released.validation,
  chapter:1,date:'2026年10月17日（土）',partner:story,savedRecords:[],recordIndices:[],storyActions:actions});
const original=JSON.stringify(save), chapterOriginal=JSON.stringify(bundle);
const prepared=C.prepareChapter(save,bundle,{runtime,sources,filename:'lite_test_char_016_0001.json'});
assert.equal(JSON.stringify(save),original,'validation never mutates the current save');
assert.equal(JSON.stringify(bundle),chapterOriginal,'input chapter remains intact');
assert.equal(prepared.save.state.session.recordsByCharacter.char_016[0].protagonist,input.protagonistInput);
assert.equal(prepared.save.state.session.recordsByCharacter.char_016[0].partner,story);
const history=prepared.save.state.session.statesByCharacter.char_016.stateHistory[0];
assert.equal(history.fingerprint,run.packet.fingerprint);
assert.equal(Object.hasOwn(history,'packet'),false);
assert.equal(Object.hasOwn(history,'protagonistInput'),false);
assert.equal(C.equal(prepared.save.state.session.statesByCharacter.char_016.currentState,run.packet.after),true);
assert.equal(C.prepareChapter(prepared.save,bundle,{runtime,sources}).alreadySaved,true,'same chapter does not append again');
function rejects(mutate,pattern){ const bad=C.clone(bundle); mutate(bad); assert.throws(()=>C.prepareChapter(save,bad,{runtime,sources}),pattern); assert.equal(JSON.stringify(save),original); }
rejects(b=>{b.saveId='lite_other';},/この物語/);
rejects(b=>{b.characterId='char_007';},/この物語/);
rejects(b=>{b.version=1;},/version 2/);
rejects(b=>{delete b.replayContext.storyActions.semanticReview;},/意味|確認|本文|レビュー/);
rejects(b=>{b.stateHistory[0].entry.changes.gratitude=3;},/指紋/);
rejects(b=>{b.records[0].entry.partner=story.replace('15℃','不明');},/本文|℃|気温|確認/);
assert.throws(()=>C.prepareChapter(save,bundle,{runtime,sources,filename:'lite_test_char_016_0001_light.json'}),/ファイル名/);
const changed=C.clone(bundle); changed.records[0].entry.partner+='別の本文';
assert.throws(()=>C.prepareChapter(prepared.save,changed,{runtime,sources}),/異なる内容/);
const workspace={version:1,activeId:save.saveId,saves:{[save.saveId]:save}};
const savedWorkspace=C.commitPrepared(workspace,prepared);
assert.equal(savedWorkspace.saves.lite_test.state.session.recordsByCharacter.char_016.length,1);
assert.equal(workspace.saves.lite_test.state.session.recordsByCharacter.char_016.length,0);
assert.throws(()=>C.commitPrepared({...workspace,activeId:null},prepared),/切り替わり/);
const changedWorkspace=C.clone(workspace); changedWorkspace.saves.lite_test.state.profile.name='変更';
assert.throws(()=>C.commitPrepared(changedWorkspace,prepared),/切り替わり/);
const storageData=new Map(),storage={getItem:key=>storageData.has(key)?storageData.get(key):null,setItem:(key,value)=>storageData.set(key,String(value))};
assert.equal(C.read(storage).activeId,null);
C.write(storage,savedWorkspace); assert.equal(C.equal(C.read(storage),savedWorkspace),true);
storageData.set(C.STORAGE_KEY,'{broken'); assert.throws(()=>C.read(storage),/変更していません/);
assert.equal(storageData.get(C.STORAGE_KEY),'{broken','corrupt data is never reset');
storageData.set(C.STORAGE_KEY,JSON.stringify(workspace));
assert.throws(()=>C.write({...storage,setItem(){throw Error('quota');}},savedWorkspace),/quota/);
assert.equal(C.read(storage).saves.lite_test.state.session.recordsByCharacter.char_016.length,0);
const prompt=C.buildPrompt(prepared.save,'Chapter2\n「またお会いしましょう。」');
assert.ok(prompt.includes('simulation-lite/AI_ENTRY.md'));
assert.ok(prompt.includes('男性限定'));
assert.ok(prompt.includes('private-game-dataや通常版の別セーブを取得・変更しない'));
const snapshot=C.handoffSnapshot(prepared.save);
assert.ok(prompt.includes(JSON.stringify(snapshot)),'handoff contains full text and the exact current state');
assert.equal(C.equal(snapshot.state.session.recordsByCharacter.char_016,prepared.save.state.session.recordsByCharacter.char_016),true);
assert.equal(C.equal(snapshot.state.session.statesByCharacter.char_016.currentState,run.packet.after),true);
assert.deepEqual(Object.keys(snapshot.state.session.statesByCharacter.char_016.stateHistory[0]).sort(),['fingerprint','scene','turn']);
assert.throws(()=>C.checkSave(snapshot),/バックアップ/);
assert.ok(JSON.stringify(snapshot).length<JSON.stringify(prepared.save).length,'history calculations are not resent');
const nextInput={protagonistInput:'Chapter2\n「ありがとう。」',changes:{gratitude:1},evidence:{gratitude:'ありがとう。'}};
const compactRunner=runtime.createRuntime({sources,save:snapshot,saveId:save.saveId,characterId:'char_016',recordIndices:[0]});
const fullRunner=runtime.createRuntime({sources,save:prepared.save,saveId:save.saveId,characterId:'char_016',recordIndices:[0]});
assert.equal(C.equal(compactRunner.runTurn(nextInput).packet,fullRunner.runTurn(nextInput).packet),true,'compact history produces exactly the same psychology packet');
const nextStory=story.replace('Chapter 1','Chapter 2').replace('15:00','15:01'),nextArgs=compactRunner.buildArgs(nextInput),nextRun=compactRunner.runTurn(nextInput);
const nextActions=reviewedActions(compactRunner.scope.RenaiGameTurnEngine,nextArgs,nextStory),nextReleased=compactRunner.releaseStory(nextInput,nextRun.packet,nextStory,nextActions);
vm.runInNewContext(sources['simulation/js/simulation_save.js'],{window:compactRunner.scope});
const nextBundle=compactRunner.scope.RenaiGameSave.createChapterBundleV2({args:nextArgs,packet:nextRun.packet,verification:nextReleased.verification,validation:nextReleased.validation,
  chapter:2,date:'2026年10月17日（土）',partner:nextStory,savedRecords:snapshot.state.session.recordsByCharacter.char_016,recordIndices:[0],storyActions:nextActions});
const second=C.prepareChapter(prepared.save,nextBundle,{runtime,sources});
assert.equal(second.save.state.session.recordsByCharacter.char_016.length,2,'later chapter replays the semantic binding from the same compact view');
assert.equal(C.equal(second.save.state.session.statesByCharacter.char_016.stateHistory[0],history),true,'full prior history is preserved');
assert.ok(prompt.includes('Chapter2\n「またお会いしましょう。」'));
assert.throws(()=>C.buildPrompt(save,''),/入力してください/);
const backup=C.makeBackup(savedWorkspace,{lite_test:'未保存の原文'}),empty={version:1,activeId:null,saves:{}};
assert.equal(C.equal(C.mergeBackup(empty,backup),savedWorkspace),true);
assert.equal(C.equal(C.mergeBackup(savedWorkspace,backup),savedWorkspace),true);
assert.throws(()=>C.mergeBackup(workspace,backup),/上書きしていません/);
assert.equal(C.equal(workspace.saves.lite_test,save),true);
const poison=C.clone(backup); poison.workspace.saves.lite_test.saveId='__proto__';
assert.throws(()=>C.mergeBackup(empty,poison),/セーブ形式/);
assert.equal(Object.prototype.polluted,undefined);
const registry=read('simulation/js/simulation_characters.js'),characters={};
for(const match of registry.matchAll(/"(simulation_character_\d{3}\.js)"/g)) vm.runInNewContext(read('simulation/js/'+match[1]),{window:characters});
for(const character of Object.values(characters.SimulationCharacters)){
  const state=JSON.parse(read('simulation/state/templates/'+character.id+'_initial_state.json'));
  const sample=C.createSave({profile:{},characterId:character.id,partnerName:character.name,initialState:state,saveId:'lite_'+character.id});
  const files=Object.fromEntries(runtime.sourcePaths(character.id).map(file=>[file,read(file)]));
  const r=runtime.createRuntime({sources:files,save:sample,saveId:sample.saveId,characterId:character.id,recordIndices:[]});
  assert.equal(r.runTurn({protagonistInput:'Chapter1\n「こんにちは。」',changes:{},evidence:{}}).verification.ok,true,character.id+' starts from its real initial psychology');
}
for(const file of ['simulation-lite/index.html','simulation-lite/app.js','simulation-lite/AI_ENTRY.md']) assert.ok(read(file).length>0);
assert.ok(read('index.html').includes('simulation-lite/index.html'),'entry is reachable from game home');
assert.ok(!/<img\b/i.test(read('simulation-lite/index.html')),'no portrait image is loaded');
console.log('Lite: chapter replay, semantic review, isolation, atomic storage, backups and handoff passed');
